"""Commit-message metrics: the Conventional Commits type mix and word frequencies.

Only the subject line is read, never the body, and nothing in a message is ever evaluated.
Merge commits are skipped (their subjects are generated by git, not written by people).
"""

from __future__ import annotations

import re
from collections import Counter
from typing import Any

from gitstory.metrics.stopwords import STOPWORDS
from gitstory.model import Commit
from gitstory.util import ratio

CONVENTIONAL_TYPES = (
    "feat", "fix", "docs", "style", "refactor", "perf", "test", "build", "ci", "chore", "revert",
)  # fmt: skip
TOP_WORDS = 30
MIN_WORD_LENGTH = 3
MAX_WORD_LENGTH = 24

_CONVENTIONAL = re.compile(
    r"(?P<type>[A-Za-z]+)(?:\((?P<scope>[^()\r\n]{0,64})\))?(?P<breaking>!)?:\s+(?=\S)"
)
_APOSTROPHE = "\N{RIGHT SINGLE QUOTATION MARK}"
_WORD = re.compile(r"[^\W\d_]+(?:['" + _APOSTROPHE + r"][^\W\d_]+)*")


def parse_conventional(subject: str) -> tuple[str, bool, str] | None:
    """Parse a Conventional Commits subject.

    Returns ``(type, breaking, rest)`` with the type lower-cased and ``rest`` being the text
    after the prefix, or ``None`` when the subject does not follow the format.
    """
    match = _CONVENTIONAL.match(subject)
    if match is None:
        return None
    return match["type"].lower(), match["breaking"] is not None, subject[match.end() :]


def tokenize(text: str) -> list[str]:
    """Split text into lower-cased words, dropping stopwords, numbers and very short/long tokens."""
    words = []
    for raw in _WORD.findall(text):
        word = raw.replace(_APOSTROPHE, "'").casefold()
        if MIN_WORD_LENGTH <= len(word) <= MAX_WORD_LENGTH and word not in STOPWORDS:
            words.append(word)
    return words


class MessageAccumulator:
    """Counts conventional-commit types and words over the commit subjects."""

    def __init__(self) -> None:
        self.considered = 0
        self.merges = 0
        self.breaking = 0
        self.types: Counter[str] = Counter()
        self.words: Counter[str] = Counter()
        self.tokens = 0

    def add(self, commit: Commit) -> None:
        """Record one commit."""
        if commit.is_merge:
            self.merges += 1
            return
        self.considered += 1
        parsed = parse_conventional(commit.subject)
        text = commit.subject
        if parsed is None:
            self.types["untyped"] += 1
        else:
            kind, breaking, text = parsed
            self.types[kind if kind in CONVENTIONAL_TYPES else "other"] += 1
            self.breaking += int(breaking)
        found = tokenize(text)
        self.tokens += len(found)
        self.words.update(found)

    def conventional_section(self) -> dict[str, Any]:
        """The ``conventional`` section: the mix of commit types."""
        known = sorted(
            ((kind, count) for kind, count in self.types.items() if kind in CONVENTIONAL_TYPES),
            key=lambda item: (-item[1], item[0]),
        )
        rows = [*known]
        rows += [(kind, self.types[kind]) for kind in ("other", "untyped") if self.types[kind]]
        typed = self.considered - self.types["untyped"]
        return {
            "considered": self.considered,
            "typed": typed,
            "share": ratio(typed, self.considered),
            "breaking": self.breaking,
            "types": [
                {"type": kind, "commits": count, "share": ratio(count, self.considered)}
                for kind, count in rows
            ],
        }

    def words_section(self, top: int = TOP_WORDS) -> dict[str, Any]:
        """The ``words`` section: the most frequent words in commit subjects."""
        ranked = sorted(self.words.items(), key=lambda item: (-item[1], item[0]))
        return {
            "tokens": self.tokens,
            "unique": len(self.words),
            "top": [{"word": word, "count": count} for word, count in ranked[:top]],
        }
